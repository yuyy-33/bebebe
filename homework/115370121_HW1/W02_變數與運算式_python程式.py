# ============================================================
# 投影片：變數與指派 Assignment
# ============================================================
age = 20              # 建立變數 age，值為 20
name = "小明"          # 字串變數
pi = 3.14159          # 浮點數

x = y = 0             # 同時指定多個變數
a, b = 3, 5           # 一次指定不同值
a, b = b, a           # 交換：a=5, b=3

print(a, b, name)

# ============================================================
# 投影片：算術運算子 Arithmetic
# ============================================================
a, b = 7, 2
print(a + b, a - b, a * b)   # 9 5 14
print(a / b)                 # 3.5  真除法
print(a // b)                # 3    整除（取商）
print(a % b)                 # 1    取餘數
print(a ** b)                # 49   次方
print(2 ** 10)               # 1024

# ============================================================
# 投影片：比較與邏輯運算子
# ============================================================
x = 10
print(x > 5, x == 10, x != 3)   # True True True

# 邏輯運算：組合條件
print(x > 0 and x < 100)        # True（兩者都成立）
print(x < 0 or x > 5)           # True（其一成立）
print(not (x == 10))            # False

# ============================================================
# 投影片：較特殊的運算子 Special Operators
# ============================================================
# 位元運算子（對二進位運算）
print(5 & 3, 5 | 3, 5 ^ 3)   # 1 7 6  AND/OR/XOR
print(5 << 1, 5 >> 1)        # 10 2   左移/右移

# 成員 in / not in（判斷是否包含）
print("a" in "cat", 3 in [1, 2, 3])   # True True

# 身分 is（是否為同一物件，注意 ≠ ==）
a = [1, 2]; b = a
print(a is b, a == [1, 2])   # True True

# 海象 := （Python 3.8+，邊指派邊回傳）
if (n := len("hello")) > 3:
    print(n)                 # 5

# ============================================================
# 投影片：字串與格式化 f-string
# ============================================================
s1 = 'hello'
s2 = "world"
print(s1 + " " + s2)      # 串接：hello world
print(s1 * 3)             # 重複：hellohellohello
print(len(s1))            # 長度：5

name, score = "小明", 92
print(f"{name} 得了 {score} 分")   # f-string 格式化

# ============================================================
# 投影片：型別轉換 Type Casting
# ============================================================
s = "42"
n = int(s)          # 字串 → 整數
f = float("3.14")   # 字串 → 浮點數
text = str(100)     # 數字 → 字串

print(n + 8)        # 50
print(int(3.9))     # 3（無條件捨去小數）
print(int("abc"))   # 錯誤：無法轉換

# ============================================================
# 投影片：input 與 print 進階
# ============================================================
# 一行輸入多個值
a, b = input("輸入兩個數（空白分隔）：").split()
a, b = int(a), int(b)
print(a + b)

# print 的 sep 與 end
print(1, 2, 3, sep="-")     # 1-2-3
print("不換行", end=" ")
print("接在同一行")

# ============================================================
# 投影片：複合指定與運算優先序
# ============================================================
x = 10
x += 5     # 等同 x = x + 5 → 15
x -= 3     # 12
x *= 2     # 24
x //= 5    # 4

# 運算優先序：先乘除、後加減，括號最優先
print(2 + 3 * 4)      # 14
print((2 + 3) * 4)    # 20

# ============================================================
# 投影片：好風格 vs 不好的風格 Style
# ============================================================
# ✗ 不好：命名無意義、沒空格、擠在一起
x=90;y=85;z=(x+y)/2
print(z)

# ✓ 好：有意義命名、運算子留空格、清楚分段
chinese = 90
english = 85
average = (chinese + english) / 2
print(f"平均：{average}")

# ============================================================
# 投影片：更多字串範例：跳脫字元與重複
# ============================================================
print("第一行\n第二行")      # \n 換行
print("姓名:\t小明")          # \t 對齊
print("=" * 20)               # 印出 20 個等號
title = "Python"
print(title.upper())          # PYTHON
print("Ha" * 3 + "!")         # HaHaHa!
print(f"{'置中':^10}")         # f-string 對齊（置中）

# ============================================================
# 投影片：綜合範例：把所學組起來 Putting It Together
# ============================================================
# 計算 BMI 並輸出
name = input("姓名：")
weight = float(input("體重(kg)："))
height = float(input("身高(cm)：")) / 100   # 轉成公尺

bmi = weight / height ** 2
print(f"{name} 的 BMI = {bmi:.1f}")

# 平均與四捨五入
s1, s2, s3 = 90, 85, 78
avg = (s1 + s2 + s3) / 3
print(f"平均：{round(avg, 1)} 分")

# ============================================================
# 投影片：步驟 1：輸入基本資料
# ============================================================
total  = float(input("總花費（外幣）："))   # 例：12000
people = int(input("同行人數："))            # 例：4
rate   = float(input("匯率 1 外幣=? 台幣："))  # 例：0.22

# ============================================================
# 投影片：步驟 2：計算每人均攤
# ============================================================
per     = total / people        # 每人均攤（外幣）
per_twd = per * rate            # 換算成台幣
print(f"每人均攤：{per:.2f}")
print(f"約合台幣：{per_twd:.0f} 元")

# ============================================================
# 投影片：步驟 3：加小費、印明細卡
# ============================================================
tip_rate  = 0.1                        # 小費 10%
total_tip = total * (1 + tip_rate)    # 含小費總額
per_tip   = total_tip / people        # 含小費每人

print("=" * 22)
print(f" 旅遊分帳明細（{people} 人）")
print(f" 每人均攤：{per:.0f}")
print(f" 含小費 ：{per_tip:.0f}")
print("=" * 22)
